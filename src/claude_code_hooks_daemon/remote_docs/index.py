"""The generated corpus index (Plan 00326 Task 5.2).

"Do we already have docs for X?" should cost one grep, not a daemon command
and not a recursive walk of frontmatter blocks.

The index deliberately lives OUTSIDE the vendored tree. Inside it, it would
have no ``source_url`` of its own and the provenance gate would deny it --
and exempting a filename from that gate would punch a hole straight through
the invariant the tree exists to hold. Outside, it is an ordinary generated
artefact, like the daemon's other ones.

It is regenerated by ``add`` and ``refresh`` rather than on demand, because
an index that silently goes stale is worse than no index: it answers "no, we
don't have that" confidently and wrongly.
"""

from pathlib import Path
from typing import Final

from claude_code_hooks_daemon.remote_docs.store import list_documents

INDEX_RELATIVE_PATH: Final[str] = ".claude/REMOTE-DOCS.md"

_HEADER: Final[str] = (
    "# Vendored remote documentation\n"
    "\n"
    "<!-- GENERATED by `hooks-daemon remote-docs`. Do not edit: this file is\n"
    "     rewritten on every capture and refresh, and your edit would be lost. -->\n"
    "\n"
    "Documentation captured from upstream and stored locally, so it can be read\n"
    "and grepped without a network round trip. Each entry names the local file\n"
    "and the URL it came from.\n"
    "\n"
    "Capture a new page:  `bin/hooks-daemon remote-docs add <url>`\n"
    "Refresh everything:  `bin/hooks-daemon remote-docs refresh --all`\n"
    "\n"
)

_EMPTY: Final[str] = "_Nothing vendored yet._\n"
_TABLE_HEAD: Final[str] = (
    "| Document | Source | Captured | Fresh until |\n"
    "| -------- | ------ | -------- | ----------- |\n"
)
_UNKNOWN: Final[str] = "—"


def render_index(tree_root: Path) -> str:
    """The index for the corpus under ``tree_root``, as markdown.

    Documents are listed in path order so a regenerated index does not churn
    the diff on every capture. An unreadable document is LISTED, with its
    unknown fields marked: omitting it would make the index quietly disagree
    with the tree it describes.
    """
    documents = list_documents(tree_root)
    if not documents:
        return _HEADER + _EMPTY

    rows = []
    for document in documents:
        try:
            shown = document.path.relative_to(tree_root)
        except ValueError:
            shown = document.path
        provenance = document.provenance
        if provenance is None:
            rows.append(f"| `{shown}` | {_UNKNOWN} | {_UNKNOWN} | unreadable provenance |")
            continue
        rows.append(
            f"| `{shown}` | {provenance.source_url} | "
            f"{provenance.fetched_at.date()} | {provenance.stale_after} |"
        )

    return _HEADER + _TABLE_HEAD + "\n".join(rows) + "\n"


def write_index(project_root: Path, tree_root: Path) -> Path:
    """Write the index for ``tree_root`` and return its path.

    Returns the path even when nothing was vendored: an empty corpus is a
    real state, and an index that says so is more useful than a missing file
    whose absence could mean either "empty" or "never generated".
    """
    destination = project_root / INDEX_RELATIVE_PATH
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(render_index(tree_root), encoding="utf-8")
    return destination
