"""ClaudeMdInjector — injects active handler guidance into project CLAUDE.md.

On daemon startup, the injector collects get_claude_md() from all active
handlers and writes a <hooksdaemon>...</hooksdaemon> section into the
project CLAUDE.md. This keeps agents informed about handler behaviour
without manual CLAUDE.md maintenance.

Usage:
    injector = ClaudeMdInjector(workspace_root=path, handlers=all_handlers)
    injector.inject()
"""

import logging
import re
import subprocess  # nosec B404 - imported for the CompletedProcess type; git spawns live in utils.git_repo
from pathlib import Path
from typing import Any, Protocol, runtime_checkable

from claude_code_hooks_daemon.constants.timeout import Timeout
from claude_code_hooks_daemon.utils.git_repo import run_git
from claude_code_hooks_daemon.utils.markdown_format import format_markdown_text

logger = logging.getLogger(__name__)

# Section delimiters — must match exactly when reading/replacing
_OPEN_TAG = "<hooksdaemon>"
_CLOSE_TAG = "</hooksdaemon>"

# Porcelain status code for a path git does not track yet. `git commit --only`
# refuses such a path ("pathspec ... did not match any file(s) known to git"),
# so it is the one case where the auto-commit must stage first.
_UNTRACKED_STATUS_PREFIX = "??"

# Substring git puts in stderr when another process holds the index lock.
_INDEX_LOCK_MARKER = "index.lock"

# Auto-generated comment inside the section
_AUTO_COMMENT = (
    "<!-- Auto-generated by hooks daemon on restart. "
    "Do not edit this section — changes will be overwritten. -->"
)

# Section header shown inside the <hooksdaemon> block
_SECTION_HEADER = "## Hooks Daemon — Active Handler Guidance\n"

# The class-wide Bash blind spot, stated ONCE (Plan 00260). Every handler that
# inspects file content or a file path keys on the Write/Edit tools, because
# `core/utils.py`'s get_file_path()/get_file_content() return None for any other
# tool — so a handler cannot opt in even if its author wanted to. Twenty-two
# handlers are affected, and a sentence in each would cost every client project
# ~22 copies of one fact on every session while reading as boilerplate. The
# second half matters as much as the first: a reader told only that Bash
# bypasses the guards could conclude Bash is unguarded generally, which is
# false and more dangerous than the gap being described.
_BASH_WRITE_BOUNDARY = (
    "**A file written through Bash is not seen by the content guards that run "
    "BEFORE the write.** The PreToolUse handlers below that inspect what a file "
    "CONTAINS, or where it lives, key on the `Write` and `Edit` tools — so a "
    "`>`, `>>`, `tee` or a `cat <<EOF` heredoc reaches disk unexamined by them: "
    "no block, no advisory, no record. **A Bash write that drew no complaint is "
    "NOT a write that passed those checks** — use `Write`/`Edit` for file "
    "content and they apply.\n\n"
    "**The LINTERS are the exception, and they DENY.** `lint_on_edit` and "
    "`validate_eslint_on_write` do run on a file a Bash command AUTHORS — a "
    "redirect, `tee`, a heredoc — so unparseable Python or failing TypeScript "
    "is reported however it reached disk. The write has already landed, so the "
    "denial is a failure report to repair with `Edit`, not a rollback. A file "
    "the command merely RELOCATES (`cp`, `mv`, `install`, `dd`) is never "
    "linted: those bytes were already on disk, so blaming the copy would "
    "report a defect the command did not introduce.\n\n"
    "The handlers that judge a Bash COMMAND — destructive git, `sed`, "
    "pipes, permissions, `curl | sh` — are unaffected and still cover you."
)

_SECTION_INTRO = (
    "The handlers listed below are active in this project. "
    "Read this section to avoid triggering unnecessary blocks.\n\n"
    "**When a tool is blocked by a handler, do not stop working.** "
    "Read the block reason, modify your approach, and continue with your task.\n\n"
    f"{_BASH_WRITE_BOUNDARY}"
)

# Provenance marker emitted before each handler's guidance (DBF, Core
# Standard 15). The injector holds `handler.name` while assembling the block;
# writing it out is what lets a checker ask "does the handler that produced
# this section still exist?". Section HEADINGS cannot answer that — they are
# whatever each `get_claude_md()` chose to write, ranging from
# `## destructive_git` to prose like `### Stop Explanation Required`, so any
# heading-based match would be part heuristic and part false-positive.
#
# An HTML comment is used because it is invisible to a human reader and
# survives `format_markdown_text` untouched, exactly as `_AUTO_COMMENT` does.
# The auto-commit deliberately commits the WHOLE file — its purpose is to stop
# an agent seeing a dirty CLAUDE.md after a restart and trying to revert it. But
# it gates only on "is the file dirty?", so a developer's in-progress edits get
# swept in too. Committing them is fine; CLAIMING they were a regeneration is
# not — that is how a real change gets skipped in review. Two messages, chosen
# by whether the diff reaches outside the generated block.
_COMMIT_MESSAGE_GENERATED = "Auto: hooks daemon regenerated CLAUDE.md handler guidance"
_COMMIT_MESSAGE_WITH_USER_EDITS = (
    "Auto: hooks daemon committed CLAUDE.md\n\n"
    "This commit CHANGES CONTENT OUTSIDE the generated <hooksdaemon> block, so\n"
    "it is not just a guidance regeneration. That content is either an\n"
    "uncommitted hand edit the daemon swept up (it commits the whole file so\n"
    "the tree is clean after a restart) or a reflow by the markdown formatter.\n"
    "Either way it warrants a look, which the regeneration message would not\n"
    "have prompted."
)
_GIT_HEAD_REF = "HEAD"

_HANDLER_MARKER_PREFIX = "<!-- handler: "
_HANDLER_MARKER_SUFFIX = " -->"
_HANDLER_MARKER_PATTERN = re.compile(
    rf"{re.escape(_HANDLER_MARKER_PREFIX)}(?P<name>[^>]+?){re.escape(_HANDLER_MARKER_SUFFIX)}"
)


def handler_names_in_guidance(content: str) -> list[str]:
    """Return the handler names recorded in ``content``'s guidance block.

    The single reader of the provenance markers, so callers never re-derive
    the format. Returns names in emission order; returns an empty list for
    content with no guidance block at all.

    Args:
        content: Full text of a ``CLAUDE.md`` (or any string).

    Returns:
        Handler names, in the order their sections appear.
    """
    open_pos = content.find(_OPEN_TAG)
    close_pos = content.find(_CLOSE_TAG)
    if open_pos == -1 or close_pos == -1 or close_pos < open_pos:
        return []
    block = content[open_pos : close_pos + len(_CLOSE_TAG)]
    return [match.group("name").strip() for match in _HANDLER_MARKER_PATTERN.finditer(block)]


@runtime_checkable
class HasClaudeMd(Protocol):
    """Protocol for handlers that can provide CLAUDE.md guidance.

    Structural protocol — any class with name: str and get_claude_md()
    satisfies this interface without explicit inheritance.
    """

    name: str

    def get_claude_md(self) -> str | None:
        """Return markdown guidance, or None to exclude from injection."""
        ...


class ClaudeMdInjector:
    """Injects active handler guidance into project CLAUDE.md.

    Reads the project CLAUDE.md, finds (or creates) a
    <hooksdaemon>...</hooksdaemon> section, and replaces its content
    with fresh guidance collected from active handlers.

    Handlers that return None from get_claude_md() are excluded.
    If no handlers have guidance, CLAUDE.md is left untouched.
    All errors (missing file, permission errors) are logged and swallowed
    — injection is advisory and must never crash the daemon.

    Safety: before writing, the injector verifies that user content
    (everything outside the <hooksdaemon> block) is preserved. If user
    content would be lost, the write is aborted and the original file
    is left untouched. A .CLAUDE.md.pre-inject backup is always written
    before modifying an existing file.
    """

    # Backup filename — written before every modification to an existing CLAUDE.md
    _BACKUP_FILENAME = ".CLAUDE.md.pre-inject"

    # How many times to recompute when CLAUDE.md changes underneath us mid-write.
    # Bounded so a pathologically busy file cannot spin forever; on exhaustion we
    # decline to write rather than discard, because a stale block is recoverable
    # (the next restart fixes it) and a discarded user edit is not.
    _MAX_RECONCILE_ATTEMPTS = 3

    def __init__(self, workspace_root: Path, handlers: list[Any]) -> None:
        """Initialise injector.

        Args:
            workspace_root: Project root containing CLAUDE.md
            handlers: All active handler instances
        """
        self._workspace_root = workspace_root
        self._handlers = handlers

    def inject(self) -> None:
        """Collect handler guidance and update CLAUDE.md.

        Silently no-ops if no handlers provide guidance.
        Logs errors but never raises — daemon startup must not fail.
        """
        try:
            self._run_inject()
        except OSError as exc:
            logger.warning(
                "ClaudeMdInjector: could not read/write %s — check file permissions (advisory skipped)",
                self._workspace_root / "CLAUDE.md",
                exc_info=exc,
            )
            return  # Advisory feature — daemon continues without CLAUDE.md injection
        except Exception as exc:  # nosec B110 - advisory, must never crash daemon
            logger.warning(
                "ClaudeMdInjector: unexpected error updating %s (advisory skipped)",
                self._workspace_root / "CLAUDE.md",
                exc_info=exc,
            )
            return  # Advisory feature — daemon continues without CLAUDE.md injection

    def _run_inject(self) -> None:
        """Execute injection — raises on errors for caller to handle."""
        sections = self._collect_sections()
        if not sections:
            logger.debug("ClaudeMdInjector: no handler guidance to inject — skipping")
            return

        generated = self._build_section(sections)
        claude_md_path = self._workspace_root / "CLAUDE.md"

        if not self._workspace_root.exists():
            logger.warning(
                "ClaudeMdInjector: workspace_root does not exist: %s", self._workspace_root
            )
            return

        if claude_md_path.exists():
            if not self._write_reconciling_concurrent_edits(claude_md_path, generated):
                return
        else:
            # No existing file — create from scratch (no backup needed)
            updated = generated + "\n"
            claude_md_path.write_text(self._format_fail_safe(updated), encoding="utf-8")

        logger.info(
            "ClaudeMdInjector: updated %s with guidance from %d handler(s)",
            claude_md_path,
            len(sections),
        )

        ClaudeMdInjector._auto_commit_if_dirty(claude_md_path)

    def _write_reconciling_concurrent_edits(self, claude_md_path: Path, generated: str) -> bool:
        """Replace the generated block without discarding anything else.

        The daemon owns the ``<hooksdaemon>`` block and nothing else, so a block
        update must not cost a single byte outside it — including bytes that
        arrive WHILE the update is being prepared. Preparing it is not
        instantaneous: ``_format_fail_safe`` shells out to the markdown
        formatter, and under load that window is wide.

        A whole-file read-modify-write across that window silently discards
        anything that landed in it. That is not theoretical — in this repository
        CLAUDE.md was written byte-identical to a snapshot taken three minutes
        earlier, dropping a line added in between, and ``_auto_commit_if_dirty``
        then committed the result so the loss left no trace.

        ``_is_user_content_preserved`` cannot see this: it compares ``original``
        against an ``updated`` derived from that same ``original``, so it checks
        the TRANSFORMATION and is blind to the file moving on. The fix is to
        re-read immediately before writing and, if the content changed,
        recompute against what is actually there now.

        Returns:
            True if the file was written, False if the write was declined. A
            declined write leaves the file exactly as the other writer left it.
        """
        original = claude_md_path.read_text(encoding="utf-8")

        for _ in range(self._MAX_RECONCILE_ATTEMPTS):
            updated = self._replace_or_append_section(original, generated)

            # SAFETY: verify user content is preserved before writing
            if not self._is_user_content_preserved(original, updated):
                logger.error(
                    "ClaudeMdInjector: CONTENT LOSS DETECTED — aborting write to %s. "
                    "User content outside <hooksdaemon> block would be lost. "
                    "Original: %d chars, updated: %d chars. "
                    "Backup at: %s",
                    claude_md_path,
                    len(original),
                    len(updated),
                    claude_md_path.parent / self._BACKUP_FILENAME,
                )
                return False

            # Write backup before modifying existing file
            backup_path = self._workspace_root / self._BACKUP_FILENAME
            backup_path.write_text(original, encoding="utf-8")

            # Canonicalise via the markdown formatter AFTER the content-loss
            # guard above (which validates the block replacement on the
            # pre-format text). Writing the formatter-canonical form here means
            # a later Write/Edit that triggers the PostToolUse
            # markdown_table_formatter produces no churn diff on our block.
            formatted = self._format_fail_safe(updated)

            # Re-read immediately before the write. This is the whole point: if
            # the file moved on, `formatted` is derived from a stale snapshot
            # and writing it would discard whatever arrived.
            current = claude_md_path.read_text(encoding="utf-8")
            if current == original:
                claude_md_path.write_text(formatted, encoding="utf-8")
                return True

            logger.warning(
                "ClaudeMdInjector: %s changed while the update was being prepared; "
                "recomputing against the current content so the concurrent edit is "
                "not discarded",
                claude_md_path,
            )
            original = current

        logger.error(
            "ClaudeMdInjector: %s kept changing while the update was being prepared "
            "(%d attempts); declining to write. The generated block may be stale until "
            "the next restart — that is recoverable, a discarded edit is not.",
            claude_md_path,
            self._MAX_RECONCILE_ATTEMPTS,
        )
        return False

    @staticmethod
    def _format_fail_safe(content: str) -> str:
        """Return content reformatted via the shared markdown formatter.

        Fail-safe: if mdformat raises (parser/unicode/IO error), the original
        unformatted content is returned so injection still completes and no
        content is lost. Daemon startup must never fail on a formatting error.
        """
        try:
            return format_markdown_text(content)
        except Exception as exc:  # nosec B110 - fail-safe: never crash daemon startup
            logger.warning(
                "ClaudeMdInjector: markdown formatting failed — writing unformatted "
                "content (advisory): %s",
                exc,
            )
            return content

    @staticmethod
    def _auto_commit_if_dirty(claude_md_path: Path) -> None:
        """Auto-commit CLAUDE.md if it has uncommitted changes.

        Prevents LLMs from seeing a dirty CLAUDE.md after daemon restart
        and attempting to revert or stash it. Only commits CLAUDE.md —
        never touches other staged files. Advisory: logs errors but
        never raises.

        Runs on the daemon STARTUP path, and a restart is mandated after every
        handler change — so this executes precisely when an agent is likely to be
        running git in the same working tree. Every git invocation therefore goes
        through :func:`run_git`, which declines git's OPTIONAL index lock: before
        that, merely asking whether CLAUDE.md was dirty rewrote the index and took
        ``.git/index.lock`` on every single start (Plan 00246).
        """
        cwd = claude_md_path.parent
        filename = str(claude_md_path.name)

        if run_git(cwd, "rev-parse", "--git-dir").returncode != 0:
            return  # Not a git repo — nothing to commit

        # Check if CLAUDE.md has changes (staged or unstaged). Costs no lock.
        status = run_git(cwd, "status", "--porcelain", filename)
        status_line = status.stdout.strip()
        if not status_line:
            return  # CLAUDE.md is clean — no commit needed

        # Stage ONLY when git does not know the path yet. `commit --only <path>`
        # scopes the commit to that path by itself, so for a tracked CLAUDE.md
        # staging is a second index lock for nothing — but on an UNTRACKED path
        # `--only` fails outright with `pathspec ... did not match any file(s)`,
        # which is what a first install has.
        if status_line.startswith(_UNTRACKED_STATUS_PREFIX):
            # GIT_COMMIT, not the default: `add` takes the same REQUIRED index
            # lock and writes the same index as the commit below, and the reason
            # that constant is 30s is that subprocess KILLS the child on expiry —
            # killing git mid-index-write is itself how `.git/index.lock` gets
            # orphaned, which is the failure this whole area exists to avoid.
            # These are the only two lock-taking writes left here, so they must
            # share a budget that cannot cause it (Plan 00248 F4).
            stage = run_git(cwd, "add", filename, timeout=Timeout.GIT_COMMIT)
            if stage.returncode != 0:
                ClaudeMdInjector._log_git_failure("staging", stage)
                return

        # Commit with a message that reflects WHAT is actually in the commit.
        commit = run_git(
            cwd,
            "commit",
            "--only",
            filename,
            "-m",
            ClaudeMdInjector._commit_message(cwd, filename, claude_md_path),
            timeout=Timeout.GIT_COMMIT,
        )
        if commit.returncode != 0:
            ClaudeMdInjector._log_git_failure("commit", commit)
            return

        logger.info("ClaudeMdInjector: auto-committed CLAUDE.md changes")

    @staticmethod
    def _log_git_failure(step: str, result: subprocess.CompletedProcess[str]) -> None:
        """Report a failed auto-commit step, loudly when the index lock is held.

        Contention with the agent's own git is the one failure mode worth
        interrupting for, because its visible symptom appears somewhere else
        entirely — a stale lock file, or an unrelated git command refusing to
        run. Anything else here is a genuinely advisory failure and stays at
        ``debug``.
        """
        reason = result.stderr.strip()
        if _INDEX_LOCK_MARKER in reason:
            logger.warning(
                "ClaudeMdInjector: auto-commit %s blocked — another git process holds "
                "the index lock (rc=%d): %s",
                step,
                result.returncode,
                reason,
            )
            return
        logger.debug(
            "ClaudeMdInjector: auto-commit %s failed (rc=%d): %s", step, result.returncode, reason
        )

    @staticmethod
    def _commit_message(cwd: Path, filename: str, claude_md_path: Path) -> str:
        """Pick the message that is TRUE of what this commit contains.

        Compares the content OUTSIDE the generated block against the committed
        version. If it differs, the commit carries hand-written changes the
        daemon did not author, and must not describe itself as a regeneration.

        A file with no committed version yet (first commit, or a rename) has
        nothing to compare against, so it keeps the plain message — there is no
        prior user content that could be silently swept in.
        """
        show = run_git(cwd, "show", f"{_GIT_HEAD_REF}:./{filename}")
        if show.returncode != 0:
            return _COMMIT_MESSAGE_GENERATED

        committed_user_content = ClaudeMdInjector._extract_user_content(show.stdout)
        current_user_content = ClaudeMdInjector._extract_user_content(
            claude_md_path.read_text(encoding="utf-8", errors="replace")
        )
        if committed_user_content == current_user_content:
            return _COMMIT_MESSAGE_GENERATED
        return _COMMIT_MESSAGE_WITH_USER_EDITS

    @staticmethod
    def _extract_user_content(content: str) -> str:
        """Return content outside the <hooksdaemon>...</hooksdaemon> block.

        If tags are not found, returns the full content (it is all user content).
        """
        open_pos = content.find(_OPEN_TAG)
        close_pos = content.find(_CLOSE_TAG)

        if open_pos != -1 and close_pos != -1 and open_pos < close_pos:
            before = content[:open_pos]
            after = content[close_pos + len(_CLOSE_TAG) :]
            return before + after

        # No valid tag pair — entire content is user content
        return content

    @staticmethod
    def _is_user_content_preserved(original: str, updated: str) -> bool:
        """Check that user content (outside hooksdaemon block) is preserved.

        Returns True if it is safe to write the updated content.
        Returns False if user content would be lost — the write must be aborted.
        """
        original_user = ClaudeMdInjector._extract_user_content(original)
        updated_user = ClaudeMdInjector._extract_user_content(updated)

        # Strip whitespace for comparison — whitespace changes are not content loss
        original_stripped = original_user.strip()
        updated_stripped = updated_user.strip()

        # If original had no user content, any result is safe
        if not original_stripped:
            return True

        # Updated must contain the same user content (stripped)
        return updated_stripped == original_stripped

    def _collect_sections(self) -> list[tuple[str, str]]:
        """Return list of (handler_name, guidance) for handlers with content."""
        result: list[tuple[str, str]] = []
        for handler in self._handlers:
            if not isinstance(handler, HasClaudeMd):
                continue
            content = handler.get_claude_md()
            if content is not None:
                result.append((handler.name, content))
        return result

    @staticmethod
    def _build_section(sections: list[tuple[str, str]]) -> str:
        """Build the full <hooksdaemon>...</hooksdaemon> block."""
        parts = [
            _OPEN_TAG,
            _AUTO_COMMENT,
            "",
            _SECTION_HEADER,
            _SECTION_INTRO,
            "",
        ]
        for name, content in sections:
            parts.append(f"{_HANDLER_MARKER_PREFIX}{name}{_HANDLER_MARKER_SUFFIX}")
            parts.append("")
            parts.append(content.strip())
            parts.append("")
        parts.append(_CLOSE_TAG)
        return "\n".join(parts)

    @staticmethod
    def _replace_or_append_section(original: str, new_section: str) -> str:
        """Replace existing <hooksdaemon> block or append at end of file."""
        open_pos = original.find(_OPEN_TAG)
        close_pos = original.find(_CLOSE_TAG)

        if open_pos != -1 and close_pos != -1 and open_pos < close_pos:
            # Replace existing section (keep everything before and after)
            before = original[:open_pos]
            after = original[close_pos + len(_CLOSE_TAG) :]
            return before + new_section + after

        # Append at end (ensure single trailing newline before section)
        stripped = original.rstrip("\n")
        return stripped + "\n\n" + new_section + "\n"
