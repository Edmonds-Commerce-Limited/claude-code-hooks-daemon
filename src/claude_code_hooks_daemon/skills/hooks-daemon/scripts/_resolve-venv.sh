#!/bin/bash
#
# _resolve-venv.sh - Shared venv Python resolver for hooks-daemon skill wrappers.
#
# Plan 00100 Phase 2: the parallel bash implementation was deleted. All
# resolution logic now lives in the Python SSOT:
#   $DAEMON_DIR/src/claude_code_hooks_daemon/daemon/paths.py::resolve-venv
#
# Plan 00103 Decision 2/3: a venv-resident bin/python is preferred for the
# SSOT call because we built it ourselves against pyproject's requires-python
# (>=3.11). The system ``python3`` may be 3.9 (RHEL/CentOS), which would
# crash paths.py module-load on the retired pre-Phase-2 ``import tomllib`` at
# module top — and even after the deferred-import fix, paths.py's TOML helper
# still requires 3.11+ when the bootstrap precondition path runs. When no
# venv-resident interpreter is discoverable, we fail loudly with a directive
# instead of silently falling back to the unversioned legacy path that v3.7.0
# retired (which is what hid the v3.9.0 field-bug regression).
#
# Sourced by daemon-cli.sh, health-check.sh, and init-handlers.sh.
#
# REQUIRES: DAEMON_DIR is set (caller-provided, e.g. $PROJECT_ROOT/.claude/hooks-daemon)
#
# SETS:     PYTHON  — path to the venv's bin/python
#
# Precedence:
#   1. $HOOKS_DAEMON_PYTHON                          — explicit override of the
#                                                       SSOT-invoking interpreter
#   2. $DAEMON_DIR/untracked/venv-*/bin/python       — first venv-resident match
#
# When neither resolves, the script exits non-zero with a stderr directive.

if [ -z "${DAEMON_DIR:-}" ]; then
    echo "❌ _resolve-venv.sh: DAEMON_DIR must be set before sourcing" >&2
    # shellcheck disable=SC2317  # unreachable when sourced, intentional exec fallback
    return 1 2>/dev/null || exit 1
fi

_rv_paths_script="$DAEMON_DIR/src/claude_code_hooks_daemon/daemon/paths.py"

if [ ! -f "$_rv_paths_script" ]; then
    echo "❌ _resolve-venv.sh: paths.py SSOT missing at $_rv_paths_script" >&2
    echo "   Reinstall the daemon: /hooks-daemon install" >&2
    unset _rv_paths_script
    # shellcheck disable=SC2317  # unreachable when sourced, intentional exec fallback
    return 5 2>/dev/null || exit 5
fi

# Discover a venv-resident bin/python to invoke paths.py with. paths.py itself
# does the proper precedence selection across all venv-* directories — we only
# need any one usable interpreter to run it under. ``-x`` follows symlinks and
# returns false for broken ones, so partial-install / cleanup-in-progress venvs
# are skipped automatically.
_rv_python_cmd=""
if [ -n "${HOOKS_DAEMON_PYTHON:-}" ]; then
    _rv_python_cmd="$HOOKS_DAEMON_PYTHON"
elif [ -n "${HOOKS_DAEMON_VENV_PATH:-}" ] && [ -x "${HOOKS_DAEMON_VENV_PATH}/bin/python" ]; then
    # Override venv: paths.py honours HOOKS_DAEMON_VENV_PATH for resolution,
    # and we need an interpreter to invoke paths.py with — use the override's
    # own ``bin/python`` so the script self-bootstraps from a single env var.
    _rv_python_cmd="${HOOKS_DAEMON_VENV_PATH}/bin/python"
else
    for _rv_candidate in "$DAEMON_DIR"/untracked/venv-*/bin/python; do
        if [ -x "$_rv_candidate" ]; then
            _rv_python_cmd="$_rv_candidate"
            break
        fi
    done
fi

if [ -z "$_rv_python_cmd" ]; then
    echo "❌ _resolve-venv.sh: no usable venv found under $DAEMON_DIR/untracked/" >&2
    echo "   Run /hooks-daemon install to create the venv." >&2
    unset _rv_paths_script _rv_candidate
    # shellcheck disable=SC2317  # unreachable when sourced, intentional exec fallback
    return 5 2>/dev/null || exit 5
fi

# Stderr is NOT silenced — Plan 00103 Decision 2: surface real failures (e.g.
# ModuleNotFoundError, broken venv) instead of hiding them behind a generic
# "venv not found" message generated by silent fallback.
if PYTHON=$("$_rv_python_cmd" "$_rv_paths_script" resolve-venv --daemon-dir "$DAEMON_DIR"); then
    :
else
    _rv_exit=$?
    echo "❌ _resolve-venv.sh: paths.py resolve-venv failed (exit $_rv_exit)" >&2
    unset _rv_paths_script _rv_python_cmd _rv_candidate _rv_exit
    # shellcheck disable=SC2317  # unreachable when sourced, intentional exec fallback
    return 5 2>/dev/null || exit 5
fi

# shellcheck disable=SC2034  # PYTHON is exported for the sourcing caller.
export PYTHON

unset _rv_paths_script _rv_python_cmd _rv_candidate
