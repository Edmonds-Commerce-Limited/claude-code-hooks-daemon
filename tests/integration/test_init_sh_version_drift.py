"""`init.sh` names a clone that is not the version the project expects (Plan 00477 Task 5.1).

The case: a checkout pulls a commit that changes ``daemon.expected_version`` in
``.claude/hooks-daemon.yaml``, so the installed clone under the gitignored
``.claude/hooks-daemon/`` is at a different version from the one the project now
expects. The Plan 00386 mismatch path already compared the clone with the tracked
``HOOKS-DAEMON.md`` header; this extends that one path (clone against the RESOLVED
expected version: the config key, then the header for a project that predates it)
rather than adding a second mechanism.

Nothing here moves the daemon. The message names what a human runs.
"""

from __future__ import annotations

import json
import re
import subprocess
from pathlib import Path
from typing import Final

from tests.integration.test_init_sh_stale_clone_version import (
    _TIMEOUT_SECONDS,
    _project,
    _rc,
    _run,
)

_CLONE: Final[str] = "3.60.0"
_NEWER: Final[str] = "3.68.0"
_OLDER: Final[str] = "3.50.0"

_PROBE: Final[str] = (
    _rc("_detect_stale_clone") + '\necho "clone=$_HOOKS_DAEMON_CLONE_VERSION '
    'expected=$_HOOKS_DAEMON_TRACKED_VERSION source=$_HOOKS_DAEMON_EXPECTED_VERSION_SOURCE"'
)


def _with_key(project: Path, value: str | None) -> Path:
    """Write the project's config, with `daemon.expected_version` when given."""
    key = "" if value is None else f'  expected_version: "{value}"\n'
    (project / ".claude" / "hooks-daemon.yaml").write_text(
        f"version: '2.0'\ndaemon:\n  log_level: INFO\n{key}handlers: {{}}\n", encoding="utf-8"
    )
    return project


def _drifted(tmp_path: Path, *, clone: str, expected: str, tracked: str | None = None) -> Path:
    return _with_key(
        _project(tmp_path, clone_version=clone, tracked_version=tracked or expected), expected
    )


def _response(project: Path) -> str:
    """The hook response a PreToolUse gets while the mismatch flag is set."""
    result = _run(
        project,
        _rc("_detect_stale_clone") + "\n"
        "_HOOKS_DAEMON_VERSION_MISMATCH=true\n"
        'emit_hook_error "PreToolUse" "daemon_startup_failed" "Failed to start"',
    )
    assert "rc=0" in result.stdout, result.stdout + result.stderr
    return result.stdout.split("rc=0\n", 1)[1]


def _context(project: Path) -> str:
    payload = json.loads(_response(project))
    text: str = payload["hookSpecificOutput"]["additionalContext"]
    return text


class TestTheConfigKeyIsTheExpectedVersion:
    def test_a_config_key_different_from_the_clone_is_drift(self, tmp_path: Path) -> None:
        result = _run(_drifted(tmp_path, clone=_CLONE, expected=_NEWER), _PROBE)
        assert "rc=0" in result.stdout, result.stderr
        assert f"clone={_CLONE} expected={_NEWER} source=config" in result.stdout

    def test_the_key_wins_over_a_tracked_header_that_agrees_with_the_clone(
        self, tmp_path: Path
    ) -> None:
        """The pull changed the config; the header is regenerated by upgrade only."""
        project = _drifted(tmp_path, clone=_CLONE, expected=_NEWER, tracked=_CLONE)
        assert "rc=0" in _run(project, _PROBE).stdout

    def test_the_key_wins_over_a_tracked_header_that_disagrees_with_the_clone(
        self, tmp_path: Path
    ) -> None:
        """The key agrees with the clone, so nothing has drifted, whatever the header says."""
        project = _drifted(tmp_path, clone=_CLONE, expected=_CLONE, tracked=_NEWER)
        assert "rc=1" in _run(project, _PROBE).stdout

    def test_no_key_falls_back_to_the_tracked_header(self, tmp_path: Path) -> None:
        project = _with_key(_project(tmp_path, clone_version=_CLONE, tracked_version=_NEWER), None)
        result = _run(project, _PROBE)
        assert f"clone={_CLONE} expected={_NEWER} source=tracked-doc" in result.stdout

    def test_no_key_and_no_header_is_silent(self, tmp_path: Path) -> None:
        """A branch install writes no key: nothing to drift from."""
        project = _with_key(_project(tmp_path, clone_version=_CLONE, tracked_version=None), None)
        assert "rc=1" in _run(project, _PROBE).stdout

    def test_an_invalid_key_reports_nothing_of_its_own(self, tmp_path: Path) -> None:
        """An invalid key keeps the state it already has (reported by provision and
        config validation); it is not overridden by the header, and not read as drift."""
        project = _with_key(_project(tmp_path, clone_version=_CLONE, tracked_version=_CLONE), "x")
        assert "rc=1" in _run(project, _PROBE).stdout

    def test_an_equal_version_is_silent(self, tmp_path: Path) -> None:
        assert "rc=1" in _run(_drifted(tmp_path, clone=_CLONE, expected=_CLONE), _PROBE).stdout


class TestTheDaemonsOwnRepositoryNeverReportsDrift:
    def test_a_root_dir_equal_to_the_project_is_silent(self, tmp_path: Path) -> None:
        project = _drifted(tmp_path, clone=_CLONE, expected=_NEWER)
        result = _run(project, 'HOOKS_DAEMON_ROOT_DIR="$PROJECT_PATH"\n' + _PROBE)
        assert "rc=1" in result.stdout, result.stderr


class TestTheMessage:
    def test_an_upgrade_names_both_versions_where_the_expected_one_came_from_and_the_command(
        self, tmp_path: Path
    ) -> None:
        context = _context(_drifted(tmp_path, clone=_CLONE, expected=_NEWER))

        assert _CLONE in context and _NEWER in context
        assert "daemon.expected_version" in context
        assert "UPGRADE" in context
        assert "DOWNGRADE" not in context
        assert f"args=upgrade {_NEWER}" in context
        assert "Use the hooks-daemon skill to upgrade" in context
        assert "/hooks-daemon upgrade" not in context

    def test_a_downgrade_is_named_as_one(self, tmp_path: Path) -> None:
        context = _context(_drifted(tmp_path, clone="3.68.0", expected=_OLDER))

        assert "DOWNGRADE" in context
        assert "3.68.0" in context and _OLDER in context
        assert f"args=upgrade {_OLDER}" in context
        assert "intended" in context.lower()

    def test_it_says_a_restart_cannot_fix_it_and_nothing_was_changed(self, tmp_path: Path) -> None:
        lowered = _context(_drifted(tmp_path, clone=_CLONE, expected=_NEWER)).lower()

        assert "restart" in lowered and "cannot" in lowered
        assert "nothing has been changed" in lowered

    def test_a_header_sourced_mismatch_keeps_the_plan_00386_wording(self, tmp_path: Path) -> None:
        """A project with no key is reported exactly as before: tracked assets, and a clone
        that is ahead of them gets the regenerate remedy."""
        project = _with_key(
            _project(tmp_path, clone_version="3.63.0", tracked_version="3.60.0"), None
        )
        lowered = _context(project).lower()

        assert "tracked assets" in lowered
        assert "generate-docs" in lowered

    def test_the_response_is_valid_json_for_every_direction(self, tmp_path: Path) -> None:
        for clone, expected in ((_CLONE, _NEWER), (_NEWER, _CLONE)):
            sub = tmp_path / f"{clone}-{expected}"
            sub.mkdir()
            payload = json.loads(_response(_drifted(sub, clone=clone, expected=expected)))
            assert payload["hookSpecificOutput"]["hookEventName"] == "PreToolUse"


class TestEnsureDaemonWiring:
    _FAILED_START: Final[str] = (
        "is_daemon_running() { return 1; }\n"
        "start_daemon() { return 1; }\n"
        "_is_ci_environment() { return 1; }\n"
        "_is_ci_enforced() { return 1; }\n"
        "_is_daemon_installed() { return 0; }\n"
    )

    def test_a_failed_start_with_a_drifted_key_sets_the_flag(self, tmp_path: Path) -> None:
        result = _run(
            _drifted(tmp_path, clone=_CLONE, expected=_NEWER),
            self._FAILED_START
            + "if ! ensure_daemon; then :; fi\n"
            + 'echo "mismatch=$_HOOKS_DAEMON_VERSION_MISMATCH"',
        )
        assert "mismatch=true" in result.stdout, result.stderr

    def test_a_running_daemon_pays_nothing_for_the_check(self, tmp_path: Path) -> None:
        """The hot path: a daemon that answers returns before any drift detection runs."""
        result = _run(
            _drifted(tmp_path, clone=_CLONE, expected=_NEWER),
            "is_daemon_running() { return 0; }\n"
            "_detect_stale_clone() { echo DETECTOR-RAN; return 0; }\n"
            "_resolve_expected_version() { echo RESOLVER-RAN; return 0; }\n"
            "ensure_daemon\n"
            'echo "done rc=$?"',
        )
        assert "done rc=0" in result.stdout, result.stderr
        assert "RAN" not in result.stdout

    def test_a_successful_start_never_reaches_the_check(self, tmp_path: Path) -> None:
        result = _run(
            _drifted(tmp_path, clone=_CLONE, expected=_NEWER),
            "is_daemon_running() { return 1; }\n"
            "start_daemon() { return 0; }\n"
            "_is_ci_environment() { return 1; }\n"
            "_is_ci_enforced() { return 1; }\n"
            "_detect_stale_clone() { echo DETECTOR-RAN; return 0; }\n"
            "ensure_daemon\n"
            'echo "done rc=$?"',
        )
        assert "done rc=0" in result.stdout, result.stderr
        assert "RAN" not in result.stdout


class TestTheCheckItselfIsCheap:
    def test_no_key_and_no_drift_spawns_no_process(self, tmp_path: Path) -> None:
        """With the key absent the whole question is answered by builtin reads: bash -x
        shows no external command run by the detector."""
        project = _with_key(_project(tmp_path, clone_version=_CLONE, tracked_version=None), None)
        result = subprocess.run(
            [
                "bash",
                "-c",
                f'source "{project / ".claude" / "init.sh"}"\n'
                'export PS4="+TRACE "\n'
                "set -x\n"
                "_detect_stale_clone || true\n"
                "set +x\n",
            ],
            capture_output=True,
            text=True,
            timeout=_TIMEOUT_SECONDS,
            env={"PATH": "/usr/bin:/bin", "HOME": str(project)},
            check=False,
        )
        # Nested command substitutions repeat the first PS4 character, hence `\++`.
        commands = re.findall(r"^\++TRACE (\S+)", result.stderr, flags=re.MULTILINE)
        # The clone-version read is one grep by contract (Plan 00386). The config read and
        # the comparison add no process: no awk, no second grep, nothing else external.
        external = {"awk", "grep", "sed", "cat", "tr", "cut", "sort", "python3", "jq"}
        assert [c for c in commands if c in external] == ["grep"], commands
