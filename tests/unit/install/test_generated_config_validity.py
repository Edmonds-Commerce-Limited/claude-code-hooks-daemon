"""The config `install.py` generates must be one the daemon can actually load.

Plan 00250 found this on a GitHub runner, not locally: a plain
``python install.py --self-install`` replaced the project's config with the
installer's built-in template, and the daemon then refused to start —

    Config Error: Configuration validation failed.
      Unknown field 'min_confidence_score' at: handlers.session_start.min_confidence_score
      Valid fields: enabled, options, priority

So every fresh install writes a file the daemon rejects. Nothing caught it
because the template was only ever checked by reading it: no test had run the
generated bytes through the validator that decides whether a daemon starts.

That is the gap this module closes. It asserts the round trip — generate with
the real function, load with the real loader, validate with the real validator —
rather than asserting anything about the template's text, so it stays true
however the template is later edited.
"""

from __future__ import annotations

import inspect
import shutil
import sys
from collections.abc import Callable
from pathlib import Path
from typing import Any

import pytest

from claude_code_hooks_daemon.config.loader import ConfigLoader
from claude_code_hooks_daemon.config.validator import ConfigValidator

_REPO_ROOT = Path(__file__).resolve().parents[3]


def _create_daemon_config() -> Callable[..., None]:
    """Import ``install.py`` from the repo root.

    Imported lazily rather than at module scope: ``install.py`` sits at the
    repository root rather than in ``src/``, so it is only importable once the
    root is on ``sys.path``, and doing that at module scope puts an import
    after a statement.
    """
    if str(_REPO_ROOT) not in sys.path:
        sys.path.insert(0, str(_REPO_ROOT))
    from install import create_daemon_config

    return create_daemon_config


def _generate_config(project_root: Path, *, self_install: bool) -> dict[str, Any]:
    """Run the real generator and load the result the way the daemon does."""
    (project_root / ".claude").mkdir(parents=True, exist_ok=True)
    _create_daemon_config()(project_root, self_install=self_install)
    loaded = ConfigLoader.load(project_root / ".claude" / "hooks-daemon.yaml")
    return dict(loaded)


@pytest.mark.parametrize("self_install", [True, False])
def test_the_generated_config_passes_the_daemons_own_validator(
    tmp_path: Path, self_install: bool
) -> None:
    """A freshly generated config must produce ZERO validation errors.

    This is the assertion that would have caught the runner failure. It uses the
    validator the daemon uses at startup, so a pass here means a daemon can
    start on a fresh install — the only property worth asserting.
    """
    config = _generate_config(tmp_path, self_install=self_install)

    errors = ConfigValidator.validate(config)

    assert errors == [], (
        "install.py generated a config the daemon would refuse to start on. "
        "A fresh install is broken until these are fixed:\n  " + "\n  ".join(errors)
    )


def test_the_shipped_example_config_passes_the_same_validator(tmp_path: Path) -> None:
    """`.claude/hooks-daemon.yaml.example` is what a CLIENT install deploys.

    The shell installer copies this file to `hooks-daemon.yaml` on a fresh
    install (`install_version.sh:438`), so it is the config most clients
    actually run — yet nothing validated it against the schema. It is checked
    here because it is the same defect class as the generated template above,
    just on the other installer, and a silently invalid example would strand a
    client with a daemon that will not start.

    Copied to a `.yaml` name first because the loader dispatches on extension
    and rejects `.example` outright — which is exactly what the installer does
    with it.
    """
    source = _REPO_ROOT / ".claude" / "hooks-daemon.yaml.example"
    assert source.is_file(), f"the installer's example config is missing: {source}"

    deployed = tmp_path / "hooks-daemon.yaml"
    shutil.copy(source, deployed)

    errors = ConfigValidator.validate(ConfigLoader.load(deployed))

    assert errors == [], (
        "the example config a client install deploys is invalid; a fresh client "
        "would get a daemon that refuses to start:\n  " + "\n  ".join(errors)
    )


class TestTheFixtureIsNotVacuous:
    """The test above passes trivially if the generator or validator no-ops."""

    def test_the_generator_actually_writes_a_file(self, tmp_path: Path) -> None:
        (tmp_path / ".claude").mkdir()
        _create_daemon_config()(tmp_path, self_install=True)
        written = tmp_path / ".claude" / "hooks-daemon.yaml"
        assert written.is_file()
        assert written.stat().st_size > 0

    def test_the_loaded_config_has_handler_sections(self, tmp_path: Path) -> None:
        """An empty dict would validate cleanly and prove nothing."""
        config = _generate_config(tmp_path, self_install=True)
        assert config.get("handlers"), "generated config carries no handlers section"

    def test_the_validator_rejects_a_known_bad_field(self) -> None:
        """The validator must actually report unknown handler fields."""
        bad: dict[str, Any] = {"handlers": {"session_start": {"version_check": {"not_a_field": 1}}}}
        assert ConfigValidator.validate(bad, validate_handler_names=False) != []


class TestForceStillBacksUpTheConfig:
    """Plan 00412 F-DEPL-4: the fix is written down sixty lines above the bug.

    `setup_claude_settings` backs up `settings.json` INCLUDING under `--force`,
    and its comment says exactly why: *"Backing up only when NOT forcing had it
    exactly backwards: --force reinstalls over an existing install, so it is
    the invocation most likely to be overwriting a customised file, and it was
    the one that overwrote with no copy at all."*

    `create_daemon_config` guarded its own backup with `and not force`. The
    reasoning had been worked out, written down, and applied to one of the two
    files it applies to.

    What is destroyed is not a generated default: it is the client's
    `handlers:`, `exclude_paths`, `extra_whitelist` and `plugins:` — the whole
    record of how they configured this daemon.
    """

    @staticmethod
    def _existing_config(project_root: Path) -> Path:
        (project_root / ".claude").mkdir(parents=True, exist_ok=True)
        config = project_root / ".claude" / "hooks-daemon.yaml"
        config.write_text("daemon:\n  exclude_paths: ['vendor/**']\n")
        return config

    def test_an_existing_config_is_preserved(self, tmp_path: Path) -> None:
        self._existing_config(tmp_path)

        _create_daemon_config()(tmp_path, self_install=True)

        backups = list((tmp_path / ".claude").glob("hooks-daemon.yaml.bak*"))
        assert len(backups) == 1
        assert "vendor/**" in backups[0].read_text()

    def test_the_function_takes_no_force_flag(self) -> None:
        """The flag is gone rather than ignored, which is the honest state.

        A parameter that no longer changes anything is a trap: the next reader
        assumes `force` still governs the backup. `create_settings_json` above
        dropped it for exactly this reason when the same bug was fixed there.
        """
        assert "force" not in inspect.signature(_create_daemon_config()).parameters

    def test_the_config_is_still_replaced(self, tmp_path: Path) -> None:
        """Preserving the old copy must not mean declining to install."""
        config = self._existing_config(tmp_path)

        _create_daemon_config()(tmp_path, self_install=True)

        assert "vendor/**" not in config.read_text()
        assert config.stat().st_size > 0

    def test_a_second_install_does_not_destroy_the_first_backup(self, tmp_path: Path) -> None:
        """The first backup holds the client's ORIGINAL file — the one worth keeping.

        `_free_backup_path` exists for this and documents the same-second
        collision; the bespoke timestamp branch here did not use it.
        """
        self._existing_config(tmp_path)
        _create_daemon_config()(tmp_path, self_install=True)
        _create_daemon_config()(tmp_path, self_install=True)

        backups = list((tmp_path / ".claude").glob("hooks-daemon.yaml.bak*"))
        assert len(backups) == 2
        assert any("vendor/**" in b.read_text() for b in backups)

    def test_a_fresh_install_leaves_no_backup(self, tmp_path: Path) -> None:
        """Nothing to preserve means nothing to clutter the directory with."""
        (tmp_path / ".claude").mkdir(parents=True, exist_ok=True)

        _create_daemon_config()(tmp_path, self_install=True)

        assert list((tmp_path / ".claude").glob("hooks-daemon.yaml.bak*")) == []
