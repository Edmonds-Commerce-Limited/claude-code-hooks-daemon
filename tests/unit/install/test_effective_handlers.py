"""Plan 00493: the upgrade names every handler whose effective state changes.

The v3.68.0 rule change (an opt-in handler with no config block no longer
runs) switched handlers off under an UNCHANGED config file, so no diff of the
file could ever show it. These tests pin the report that does: the effective
enabled-handler set of the client's actual config under the old and the new
resolution rules, from the same ``handler_is_enabled`` the daemon dispatches
through.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Final

import pytest
import yaml

from claude_code_hooks_daemon.daemon.init_config import generate_config
from claude_code_hooks_daemon.handlers.registry import iter_builtin_handler_classes
from claude_code_hooks_daemon.install.config_cli import run_check_effective_handlers
from claude_code_hooks_daemon.install.effective_handlers import (
    HandlerChange,
    effective_handler_changes,
    format_changes,
    restore_snippet,
)

#: The 11 opt-in blocks an `init full` config generated by v3.40-v3.54 lacks
#: (the investigation's template-history table).
_V350_MISSING_BLOCKS: Final[frozenset[str]] = frozenset(
    {
        "goal_injection",
        "flaggable_content_channel_guard",
        "flaggable_work_advisor",
        "quarantine_artefact_read_guard",
        "subagent_full_qa_blocker",
        "model_fallback_detector",
        "routine_qa_sweep",
        "session_actions_directive",
        "skill_opportunity_detector",
        "tool_disable_advisor",
        "host_hostname",
    }
)

#: Introduced by v3.68.0, so it never ran under the old rule.
_NEW_IN_V368: Final[str] = "plan_fact_check_feed"


def _opt_in_keys() -> set[str]:
    return {
        ref.config_key
        for ref in iter_builtin_handler_classes()
        if not ref.handler_cls.default_enabled
    }


def _minimal() -> dict[str, Any]:
    loaded = yaml.safe_load(generate_config("minimal"))
    assert isinstance(loaded, dict)
    return loaded


def _full() -> dict[str, Any]:
    loaded = yaml.safe_load(generate_config("full"))
    assert isinstance(loaded, dict)
    return loaded


def _full_as_generated_by_v350() -> dict[str, Any]:
    config = _full()
    for event_block in config["handlers"].values():
        if isinstance(event_block, dict):
            for key in _V350_MISSING_BLOCKS:
                event_block.pop(key, None)
    return config


def _keys(changes: list[HandlerChange]) -> set[str]:
    return {change.config_key for change in changes}


class TestEffectiveHandlerChanges:
    """The report for the three fixtures the plan names."""

    def test_minimal_config_loses_every_pre_existing_opt_in_handler(self) -> None:
        changes = effective_handler_changes(_minimal(), "3.67.0", "3.68.0")

        assert _keys(changes) == _opt_in_keys() - {_NEW_IN_V368}
        assert {change.change for change in changes} == {"stops"}

    def test_v350_full_config_loses_exactly_its_eleven_missing_blocks(self) -> None:
        changes = effective_handler_changes(_full_as_generated_by_v350(), "3.67.0", "3.68.0")

        assert _keys(changes) == _V350_MISSING_BLOCKS

    def test_v367_full_config_loses_nothing(self) -> None:
        assert effective_handler_changes(_full(), "3.67.0", "3.68.0") == []

    def test_no_change_when_both_versions_share_the_new_rule(self) -> None:
        assert effective_handler_changes(_minimal(), "3.68.0", "3.69.0") == []

    def test_a_present_bare_or_options_only_block_stays_enabled(self) -> None:
        config = _minimal()
        config["handlers"]["pre_tool_use"]["lsp_enforcement"] = {"options": {}}
        config["handlers"]["pre_tool_use"]["flaggable_work_advisor"] = None

        keys = _keys(effective_handler_changes(config, "3.67.0", "3.68.0"))

        assert "lsp_enforcement" not in keys
        assert "flaggable_work_advisor" not in keys

    def test_default_on_handlers_are_never_reported(self) -> None:
        keys = _keys(effective_handler_changes(_minimal(), "3.67.0", "3.68.0"))

        default_on = {
            ref.config_key
            for ref in iter_builtin_handler_classes()
            if ref.handler_cls.default_enabled
        }
        assert keys.isdisjoint(default_on)

    def test_branch_install_version_suffix_is_tolerated(self) -> None:
        changes = effective_handler_changes(_minimal(), "v3.67.0", "3.68.0+branch.abc1234")

        assert changes

    def test_unparseable_version_fails_fast(self) -> None:
        with pytest.raises(ValueError, match="Invalid version"):
            effective_handler_changes(_minimal(), "not-a-version", "3.68.0")


class TestRestoreSnippet:
    def test_snippet_is_valid_yaml_that_enables_each_handler_under_its_event(self) -> None:
        changes = effective_handler_changes(_minimal(), "3.67.0", "3.68.0")

        parsed = yaml.safe_load(restore_snippet(changes))

        for change in changes:
            assert parsed["handlers"][change.event][change.config_key] == {"enabled": True}

    def test_applying_the_snippet_restores_the_old_effective_set(self) -> None:
        config = _minimal()
        changes = effective_handler_changes(config, "3.67.0", "3.68.0")
        restored = yaml.safe_load(restore_snippet(changes))
        for event, blocks in restored["handlers"].items():
            config["handlers"].setdefault(event, {}).update(blocks)

        assert effective_handler_changes(config, "3.67.0", "3.68.0") == []


class TestFormatChanges:
    def test_text_names_every_handler_and_carries_the_snippet(self) -> None:
        changes = effective_handler_changes(_minimal(), "3.67.0", "3.68.0")

        text = format_changes(changes, "3.67.0", "3.68.0")

        assert "STOP" in text
        for change in changes:
            assert change.config_path in text
        assert "enabled: true" in text


class TestRunCheckEffectiveHandlers:
    """The CLI payload the upgrade script reads."""

    def _write(self, tmp_path: Path, config: dict[str, Any]) -> Path:
        path = tmp_path / "hooks-daemon.yaml"
        path.write_text(yaml.safe_dump(config), encoding="utf-8")
        return path

    def test_json_payload_lists_changes_and_snippet(self, tmp_path: Path) -> None:
        path = self._write(tmp_path, _minimal())

        result = run_check_effective_handlers("3.67.0", "3.68.0", path, "json")

        assert result["has_changes"] is True
        assert {c["config_key"] for c in result["changes"]} == _opt_in_keys() - {_NEW_IN_V368}
        assert "enabled: true" in result["restore_snippet"]
        json.dumps(result)

    def test_clean_config_reports_no_changes(self, tmp_path: Path) -> None:
        path = self._write(tmp_path, _full())

        result = run_check_effective_handlers("3.67.0", "3.68.0", path, "text")

        assert result["has_changes"] is False
        assert result["changes"] == []

    def test_missing_config_fails_fast(self, tmp_path: Path) -> None:
        with pytest.raises(FileNotFoundError):
            run_check_effective_handlers("3.67.0", "3.68.0", tmp_path / "absent.yaml", "text")
