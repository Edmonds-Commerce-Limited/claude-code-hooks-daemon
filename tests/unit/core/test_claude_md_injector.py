def _seed_repo_without_a_claude_md(root: Path) -> None:
    """A committed git repo whose tree contains NO ``CLAUDE.md``.

    Both callers need that specific absence, which the module's shared fixtures
    cannot provide — they commit a ``CLAUDE.md`` as part of setup, so the
    first-write and first-`git add` paths are invisible to them. Extracted because
    the twelve lines were duplicated verbatim (Plan 00253).

    Identity is set LOCALLY rather than inherited: a fresh repo has none, a
    developer's global config silently supplies one, and CI has none at all — so a
    test that commits without setting it passes locally and fails on a runner.
    That class cost seven occurrences across Plans 00245/00248; see
    ``tests/conftest.py``'s ``tmp_git_repo``, and Plan 00252 for the guard.
    """
    subprocess.run(["git", "init"], cwd=root, capture_output=True, check=True)
    for key, value in (
        ("user.email", "t@t"),
        ("user.name", "t"),
        # Signing is ambient too: a global `commit.gpgsign=true` fails every
        # commit here with "gpg failed to sign the data".
        ("commit.gpgsign", "false"),
        ("tag.gpgsign", "false"),
    ):
        subprocess.run(
            ["git", "config", "--local", key, value],
            cwd=root,
            capture_output=True,
            check=True,
        )
    (root / "seed.txt").write_text("seed\n")
    subprocess.run(["git", "add", "seed.txt"], cwd=root, capture_output=True, check=True)
    subprocess.run(["git", "commit", "-m", "seed"], cwd=root, capture_output=True, check=True)


def _init_git_repo(path: Path) -> None:
    """Initialise a git repo with an initial commit containing CLAUDE.md."""
    subprocess.run(["git", "init"], cwd=path, capture_output=True, check=True)
    subprocess.run(
        ["git", "config", "user.email", "test@test.com"], cwd=path, capture_output=True, check=True
    )
    subprocess.run(
        ["git", "config", "user.name", "Test"], cwd=path, capture_output=True, check=True
    )
    claude_md = path / "CLAUDE.md"
    claude_md.write_text("# Project\n")
    subprocess.run(["git", "add", "CLAUDE.md"], cwd=path, capture_output=True, check=True)
    subprocess.run(["git", "commit", "-m", "Initial"], cwd=path, capture_output=True, check=True)


class _StubHandler:
    """Minimal handler stub satisfying HasClaudeMd Protocol for injection tests."""

    def __init__(
        self,
        name: str,
        claude_md: str | None,
        rules: "list[Any] | None" = None,
    ) -> None:
        self.name = name
        self._claude_md = claude_md
        self._rules = rules if rules is not None else []

