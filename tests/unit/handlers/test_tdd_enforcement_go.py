"""tdd_enforcement on real Go module layouts (Plan 00527 Phase 3)."""

from pathlib import Path
from typing import Any

import pytest

from claude_code_hooks_daemon.handlers.pre_tool_use.tdd_enforcement import TddEnforcementHandler


def _write(path: Path, content: str = "package p\n") -> dict[str, Any]:
    return {"tool_name": "Write", "tool_input": {"file_path": str(path), "content": content}}


@pytest.fixture
def module(tmp_path: Path) -> Path:
    root = tmp_path / "app"
    root.mkdir()
    (root / "go.mod").write_text("module example.com/app\n")
    return root


@pytest.fixture
def handler() -> TddEnforcementHandler:
    return TddEnforcementHandler()


def test_root_level_package_is_enforced(handler: TddEnforcementHandler, module: Path) -> None:
    assert handler.matches(_write(module / "lib.go")) is True


def test_top_level_package_dir_is_enforced(handler: TddEnforcementHandler, module: Path) -> None:
    (module / "server").mkdir()
    assert handler.matches(_write(module / "server" / "server.go")) is True


def test_new_file_in_tested_package_passes(handler: TddEnforcementHandler, module: Path) -> None:
    pkg = module / "server"
    pkg.mkdir()
    (pkg / "server_test.go").write_text("package server\n")
    assert handler.matches(_write(pkg / "routes.go")) is False


def test_doc_go_passes(handler: TddEnforcementHandler, module: Path) -> None:
    (module / "api").mkdir()
    assert handler.matches(_write(module / "api" / "doc.go")) is False


def test_cmd_main_passes(handler: TddEnforcementHandler, module: Path) -> None:
    (module / "cmd" / "tool").mkdir(parents=True)
    assert handler.matches(_write(module / "cmd" / "tool" / "main.go")) is False


def test_generated_header_passes(handler: TddEnforcementHandler, module: Path) -> None:
    header = "// Code generated by mockgen. DO NOT EDIT.\n\npackage mocks\n"
    assert handler.matches(_write(module / "mock_store.go", header)) is False


def test_generated_name_passes(handler: TddEnforcementHandler, module: Path) -> None:
    assert handler.matches(_write(module / "api.pb.go")) is False


def test_file_outside_any_module_is_not_gated(
    handler: TddEnforcementHandler, tmp_path: Path
) -> None:
    assert handler.matches(_write(tmp_path / "scratch.go")) is False


def test_vendor_inside_module_is_not_gated(handler: TddEnforcementHandler, module: Path) -> None:
    (module / "vendor" / "x").mkdir(parents=True)
    assert handler.matches(_write(module / "vendor" / "x" / "x.go")) is False
