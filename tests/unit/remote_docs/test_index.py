"""The generated corpus index (Plan 00326 Task 5.2).

"Do we already have docs for X?" should cost one grep, not a daemon command
and not a recursive walk of frontmatter blocks.

The index lives OUTSIDE the vendored tree on purpose. Inside it, the file
would have no `source_url` of its own and would be denied by the provenance
gate — and exempting a filename from that gate would punch a hole straight
through the invariant the tree exists to hold.

It is regenerated by `add` and `refresh` rather than on demand, because an
index that silently goes stale is worse than no index: it answers "no we
don't have that" confidently and wrongly.
"""

from datetime import UTC, datetime
from pathlib import Path

from claude_code_hooks_daemon.remote_docs.index import render_index, write_index
from claude_code_hooks_daemon.remote_docs.store import write_capture

_NOW = datetime(2026, 9, 3, 10, 0, tzinfo=UTC)


def _fetch(body: bytes = b"# Upstream\n"):
    def fetch_fn(url: str) -> bytes:
        return body

    return fetch_fn


def _seed(tree: Path, url: str, licence: str = "CC-BY-4.0") -> Path:
    return write_capture(tree, url, fetch_fn=_fetch(), now=_NOW, licence=licence)


class TestRender:
    def test_an_empty_corpus_still_renders(self, tmp_path: Path) -> None:
        """A tree that exists but holds nothing is a real state, not an error."""
        assert render_index(tmp_path) != ""

    def test_each_document_contributes_its_url(self, tmp_path: Path) -> None:
        _seed(tmp_path, "https://example.com/docs/page")

        assert "https://example.com/docs/page" in render_index(tmp_path)

    def test_each_document_contributes_its_path(self, tmp_path: Path) -> None:
        _seed(tmp_path, "https://example.com/docs/page")

        assert "example.com/docs/page.md" in render_index(tmp_path)

    def test_the_capture_date_is_shown(self, tmp_path: Path) -> None:
        _seed(tmp_path, "https://example.com/docs/page")

        assert "2026-09-03" in render_index(tmp_path)

    def test_documents_are_ordered_deterministically(self, tmp_path: Path) -> None:
        """A regenerated index must not churn the diff on every capture."""
        _seed(tmp_path, "https://example.com/b")
        _seed(tmp_path, "https://example.com/a")

        first = render_index(tmp_path)
        second = render_index(tmp_path)

        assert first == second
        assert first.index("example.com/a.md") < first.index("example.com/b.md")

    def test_an_unreadable_document_is_listed_rather_than_hidden(
        self, tmp_path: Path
    ) -> None:
        """Omitting it would make the index quietly disagree with the tree."""
        bad = tmp_path / "example.com" / "bad.md"
        bad.parent.mkdir(parents=True)
        bad.write_text("# no frontmatter\n", encoding="utf-8")

        assert "bad.md" in render_index(tmp_path)

    def test_the_index_says_it_is_generated(self, tmp_path: Path) -> None:
        """Otherwise someone edits it and loses the edit on the next capture."""
        rendered = render_index(tmp_path).lower()

        assert "generated" in rendered

    def test_the_index_names_the_capture_command(self, tmp_path: Path) -> None:
        assert "remote-docs add" in render_index(tmp_path)


class TestWrite:
    def test_it_writes_outside_the_vendored_tree(self, tmp_path: Path) -> None:
        """Inside, it would have no provenance and the gate would deny it."""
        tree = tmp_path / "remote-docs"
        _seed(tree, "https://example.com/p")

        written = write_index(tmp_path, tree)

        assert tree not in written.parents

    def test_it_creates_missing_parent_directories(self, tmp_path: Path) -> None:
        tree = tmp_path / "remote-docs"
        _seed(tree, "https://example.com/p")

        assert write_index(tmp_path, tree).is_file()

    def test_rewriting_is_idempotent(self, tmp_path: Path) -> None:
        tree = tmp_path / "remote-docs"
        _seed(tree, "https://example.com/p")

        first = write_index(tmp_path, tree).read_text(encoding="utf-8")
        second = write_index(tmp_path, tree).read_text(encoding="utf-8")

        assert first == second
