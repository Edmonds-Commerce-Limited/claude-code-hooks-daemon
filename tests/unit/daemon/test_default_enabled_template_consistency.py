"""Drift guard: config template `enabled:` flags ⇔ Handler.get_default_enabled().

Plan 00133 Phase 1. `Handler.get_default_enabled()` is the code-level single
source of truth for whether a handler is opt-in (off-by-default) or opt-out
(on-by-default). The full config template generated by
``ConfigTemplate.generate_full`` is what a fresh ``init`` writes; this test
locks the two together so they can never silently drift:

  - The set of handlers the template marks ``enabled: false`` must equal the
    set of handlers whose class declares ``get_default_enabled() -> False``.

Currently the only opt-in handler is ``lsp_enforcement``
(``recovery_cron_advisor`` is opt-OUT / on by default). When a new opt-in
handler is added, BOTH the template entry and the handler override must be
updated, and this test enforces that they agree.
"""

from __future__ import annotations

from typing import Any

import yaml

from claude_code_hooks_daemon.daemon.init_config import ConfigTemplate
from claude_code_hooks_daemon.handlers.pre_tool_use.lsp_enforcement import (
    LspEnforcementHandler,
)
from claude_code_hooks_daemon.handlers.registry import HandlerRegistry, _get_config_key

# The known opt-in (off-by-default) handlers, by config_key. Update this set
# (and the corresponding handler override + template entry) when adding a new
# opt-in handler.
_EXPECTED_OPT_IN_CONFIG_KEYS = {
    "bash_safe_mode",
    "lsp_enforcement",
    "context_sidecar",
    "compaction_signal",
    "daemon_stats",
    "idle_housekeeping_advisory",
    "goal_injection",
    "skill_opportunity_detector",
}


def _template_disabled_config_keys() -> set[str]:
    """config_keys marked ``enabled: false`` anywhere in the full template."""
    parsed = yaml.safe_load(ConfigTemplate.generate_full())
    disabled: set[str] = set()
    for _event, handlers in (parsed.get("handlers") or {}).items():
        if not isinstance(handlers, dict):
            continue
        for name, cfg in handlers.items():
            if isinstance(cfg, dict) and cfg.get("enabled") is False:
                disabled.add(name)
    return disabled


def _handler_opt_in_config_keys() -> set[str]:
    """config_keys of discovered handler classes that declare opt-in default."""
    registry = HandlerRegistry()
    registry.discover()
    opt_in: set[str] = set()
    for class_name in registry.list_handlers():
        cls = registry.get_handler_class(class_name)
        if cls is None:
            continue
        # get_default_enabled needs no state beyond `self`; read it off the
        # function with a throwaway object to avoid instantiating handlers that
        # may have heavier __init__ side effects.
        default_enabled = cls.get_default_enabled(cls.__new__(cls))
        if default_enabled is False:
            opt_in.add(_get_config_key(class_name))
    return opt_in


class TestDefaultEnabledTemplateConsistency:
    def test_lsp_enforcement_is_opt_in(self) -> None:
        assert (
            LspEnforcementHandler.get_default_enabled(
                LspEnforcementHandler.__new__(LspEnforcementHandler)
            )
            is False
        )

    def test_daemon_stats_is_opt_in(self) -> None:
        """daemon_stats (uptime/memory/log-level) is off by default -- not useful
        to normal users; the daemon-upgrade notifier (version_check) stays on."""
        from claude_code_hooks_daemon.handlers.status_line.daemon_stats import (
            DaemonStatsHandler,
        )

        assert (
            DaemonStatsHandler.get_default_enabled(DaemonStatsHandler.__new__(DaemonStatsHandler))
            is False
        )

    def test_template_marks_only_expected_handlers_disabled(self) -> None:
        assert _template_disabled_config_keys() == _EXPECTED_OPT_IN_CONFIG_KEYS

    def test_handler_overrides_match_expected(self) -> None:
        assert _handler_opt_in_config_keys() == _EXPECTED_OPT_IN_CONFIG_KEYS

    def test_template_and_handlers_agree(self) -> None:
        """The two independent sources of truth must be identical (no drift)."""
        assert _template_disabled_config_keys() == _handler_opt_in_config_keys()


class TestGeneratedTemplateHasNoDuplicateKeys:
    """The generated config must survive a STRICT YAML loader.

    PyYAML's ``safe_load`` silently tolerates duplicate mapping keys (last
    wins), which is precisely why a duplicated handler entry sat in the
    template unnoticed: every existing test parsed it with ``safe_load``, so
    the defect was invisible to the tooling meant to catch it. A user running
    ``yamllint``, ``yq`` or a strict schema validator against a config the
    daemon itself generated would get an error.

    Duplicate detection needs the NODE tree, not constructed objects — by the
    time a mapping is built the duplicate has already been collapsed. So this
    composes rather than loads, which also means nothing is ever constructed
    from the document.
    """

    def test_generate_full_has_no_duplicate_keys(self) -> None:
        import yaml

        root = yaml.compose(ConfigTemplate.generate_full(), Loader=yaml.SafeLoader)

        duplicates: list[str] = []

        def _walk(node: yaml.Node) -> None:
            if isinstance(node, yaml.MappingNode):
                seen: set[str] = set()
                for key_node, value_node in node.value:
                    key = getattr(key_node, "value", None)
                    if isinstance(key, str):
                        if key in seen:
                            duplicates.append(f"{key!r} at line {key_node.start_mark.line + 1}")
                        seen.add(key)
                    _walk(value_node)
            elif isinstance(node, yaml.SequenceNode):
                for item in node.value:
                    _walk(item)

        assert root is not None
        _walk(root)

        assert not duplicates, (
            "The generated config contains duplicate YAML keys, which a "
            "strict loader (yamllint, yq, a schema validator) rejects:\n  "
            + "\n  ".join(duplicates)
        )


